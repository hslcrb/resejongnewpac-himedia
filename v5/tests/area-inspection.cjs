const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
    const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH || 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe', args: ['--enable-webgl','--use-angle=swiftshader','--enable-unsafe-swiftshader'] });
    try {
        const page = await browser.newPage({ viewport: { width: 1200, height: 900 } });
        const errors=[];page.on('pageerror', error => errors.push(error.message));
        await page.goto((process.env.AREA_TEST_ORIGIN || 'http://127.0.0.1:3137') + '/v5/visit/area/');
        await page.getByRole('status').filter({hasText:'세종문화회관과 광화문 주변'}).waitFor({timeout:120000});
        await page.getByRole('button',{name:'돋보기',exact:true}).click();
        assert.equal(await page.getByRole('button',{name:'돋보기',exact:true}).getAttribute('aria-pressed'),'true');
        await page.locator('.area-stage canvas').first().click({position:{x:500,y:300}});
        await page.getByRole('status').filter({hasText:'선택 지점 주변 건물'}).waitFor({timeout:60000});
        await page.getByRole('button',{name:'현재 중심 건물 조회'}).click();
        await page.getByRole('status').filter({hasText:'중심 주변 건물'}).waitFor({timeout:60000});
        await page.getByRole('heading',{name:'돋보기 · 건물 정보'}).waitFor();
        assert.equal(await page.locator('.area-building').first().locator('dt').count(),29);
        assert.ok((await page.locator('.area-building').first().innerText()).includes('법정동명'));
        await page.getByRole('button',{name:'전시천리안 (全視千里眼)'}).click();
        assert.equal(await page.getByRole('button',{name:'전시천리안 (全視千里眼)'}).getAttribute('aria-pressed'),'true');
        await page.getByRole('heading',{name:'전시천리안 · 건물 정보'}).waitFor();
        await page.getByRole('status').filter({hasText:'건물 위치 695,753건'}).waitFor({timeout:60000});
        assert.equal(await page.locator('.area-projection').isVisible(),true);
        await page.locator('.area-stage canvas').first().click({position:{x:500,y:300}});
        await page.getByRole('status').filter({hasText:'선택 지점 주변 건물'}).waitFor({timeout:15000});
        assert.equal(await page.locator('.area-building').first().locator('dt').count(),29);
        await page.getByRole('button',{name:'서울 전체 자료'}).click();
        await page.getByText(/전체 695,753건/).waitFor({timeout:30000});
        await page.getByRole('status').filter({hasText:'선택 지역'}).waitFor({timeout:60000});
        assert.equal(await page.locator('#building-tile option').count(),664);
        assert.equal(await page.locator('.area-building').first().locator('dt').count(),29);
        const first=await page.locator('.area-building').first().innerText();
        await page.getByRole('button',{name:'다음 건물'}).click();
        assert.notEqual(await page.locator('.area-building').first().innerText(),first);
        await page.getByLabel('서울 전체 주소·건물명 검색').fill('세종로 81-3');
        await page.getByRole('button',{name:'전체 검색',exact:true}).click();
        await page.getByRole('status').filter({hasText:/검색 결과 [1-9]/}).waitFor({timeout:120000});
        const globalResults=page.getByRole('list',{name:'서울 전체 검색 결과'});
        await globalResults.getByRole('button').first().click();
        await page.getByRole('status').filter({hasText:'선택한 건물의 모든 필드'}).waitFor({timeout:30000});
        assert.match(await page.locator('.area-building').first().innerText(),/세종로 81-3/);
        assert.equal(await page.locator('.area-building').first().locator('dt').count(),29);
        await page.route('**/area/buildings/*.json.gz', async route => { await new Promise(resolve => setTimeout(resolve, 1800)); await route.continue(); });
        await page.getByRole('button',{name:'서울 전역'}).click();
        await page.getByRole('status').filter({hasText:'서울 전역과 광화문 주변'}).waitFor({timeout:120000});
        const started=Date.now();
        await page.locator('.area-stage canvas').first().click({position:{x:500,y:300}});
        await page.getByRole('status').filter({hasText:'선택 지점 주변 건물'}).waitFor({timeout:30000});
        console.log('Seoul magnifier response ms:',Date.now()-started);
        await page.waitForTimeout(2000);
        await page.getByRole('status').filter({hasText:'선택 지점 주변 건물'}).waitFor({timeout:5000});
        assert.deepEqual(errors,[]);
        console.log('PASS: magnifier, nearby records, 29 fields, projection, all 695753 records across 664 areas, paging');
    } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exitCode=1});
