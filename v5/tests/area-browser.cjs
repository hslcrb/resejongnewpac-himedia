const { chromium } = require('playwright');
const path = require('node:path');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const origin = process.env.AREA_TEST_ORIGIN || 'http://127.0.0.1:3137';
(async () => {
    const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH || 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe', args: ['--enable-webgl','--use-angle=swiftshader','--enable-unsafe-swiftshader'] });
    try {
        const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
        const errors = [];
        const requests = [];
        page.on('pageerror', error => errors.push(error.message));
        page.on('request', request => requests.push(request.url()));
        await page.goto(origin + '/v5/visit/area/', { waitUntil: 'domcontentloaded', timeout: 120000 });
        await page.getByRole('status').filter({ hasText: '세종문화회관과 광화문 주변' }).waitFor({ timeout: 120000 });
        assert.equal(await page.locator('.area-stage canvas').count(), 1);
        assert.equal(requests.some(url => url.includes('seoul-grid.json')), false, '서울 자료는 초기 화면에서 불러오지 않는다');
        assert.equal(await page.getByRole('button', { name: '광화문 주변' }).getAttribute('aria-pressed'), 'true');
        await page.locator('.area-explorer').screenshot({ path: path.resolve('../gis-sejong/web/evidence-local.png') });
        await page.getByRole('button', { name: '서울 전역' }).click();
        await page.getByRole('status').filter({ hasText: '서울 전역과 광화문 주변' }).waitFor({ timeout: 120000 });
        assert.equal(await page.getByRole('button', { name: '서울 전역' }).getAttribute('aria-pressed'), 'true');
        assert.equal(requests.filter(url => url.includes('seoul-grid.json')).length, 1);
        await page.locator('.area-explorer').screenshot({ path: path.resolve('../gis-sejong/web/evidence-seoul.png') });
        const beforeRotate = await page.locator('.area-stage canvas').screenshot();
        await page.getByRole('button', { name: '왼쪽 회전' }).click();
        const afterRotate = await page.locator('.area-stage canvas').screenshot();
        assert.notEqual(crypto.createHash('sha256').update(beforeRotate).digest('hex'), crypto.createHash('sha256').update(afterRotate).digest('hex'), '회전 버튼이 장면을 바꿔야 한다');
        await page.getByRole('button', { name: '확대', exact: true }).click();
        await page.getByRole('button', { name: '처음 보기' }).click();
        await page.getByRole('button', { name: '광화문 주변' }).click();
        await page.getByRole('status').filter({ hasText: '세종문화회관과 광화문 주변' }).waitFor({ timeout: 30000 });
        await page.setViewportSize({ width: 390, height: 844 });
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, '모바일 가로 넘침');
        await page.locator('.area-explorer').screenshot({ path: path.resolve('../gis-sejong/web/evidence-mobile.png') });
        assert.deepEqual(errors, []);
        await page.close();
        const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1 });
        await mobile.goto(origin + '/v5/visit/area/', { waitUntil: 'domcontentloaded', timeout: 120000 });
        await mobile.getByRole('status').filter({ hasText: '세종문화회관과 광화문 주변' }).waitFor({ timeout: 120000 });
        await mobile.locator('.area-explorer').screenshot({ path: path.resolve('../gis-sejong/web/evidence-mobile-initial.png') });
        assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
        await mobile.getByRole('button', { name: '서울 전역' }).click();
        await mobile.getByRole('status').filter({ hasText: '서울 전역과 광화문 주변' }).waitFor({ timeout: 120000 });
        await mobile.locator('.area-explorer').screenshot({ path: path.resolve('../gis-sejong/web/evidence-mobile-seoul.png') });
        await mobile.close();
        const failure = await browser.newPage({ viewport: { width: 1024, height: 800 } });
        await failure.route('**/area/seoul-grid.json', route => route.abort());
        await failure.goto(origin + '/v5/visit/area/', { waitUntil: 'domcontentloaded', timeout: 120000 });
        await failure.getByRole('status').filter({ hasText: '세종문화회관과 광화문 주변' }).waitFor({ timeout: 120000 });
        await failure.getByRole('button', { name: '서울 전역' }).click();
        await failure.getByRole('status').filter({ hasText: '서울 전역을 불러오지 못했습니다' }).waitFor({ timeout: 30000 });
        await failure.unroute('**/area/seoul-grid.json');
        await failure.getByRole('button', { name: '다시 불러오기' }).click();
        await failure.getByRole('status').filter({ hasText: '서울 전역과 광화문 주변' }).waitFor({ timeout: 120000 });
        await failure.close();
        console.log('PASS: local load, lazy Seoul, switch, rotation, zoom/reset, initial mobile modes and failed-load retry');
    } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
